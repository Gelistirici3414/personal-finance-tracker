import os
from flask import Blueprint, render_template, request, redirect, url_for, flash, session
from models import db, UpcomingPayment, Transaction, Account
from datetime import datetime

debts_bp = Blueprint('debts', __name__)

@debts_bp.route('/')
def list_debts():
    uid = session['user_id']
    debts = UpcomingPayment.query.filter(
        UpcomingPayment.user_id == uid,
        UpcomingPayment.category.ilike('%debt%')
    ).order_by(UpcomingPayment.due_date.asc()).all()
    return render_template('debts.html', debts=debts)

@debts_bp.route('/add', methods=['GET', 'POST'])
def add_debt():
    if request.method == 'POST':
        uid = session['user_id']
        title = request.form.get('title')
        amount = float(request.form.get('amount'))
        due_date_str = request.form.get('due_date')
        due_date = datetime.strptime(due_date_str, '%Y-%m-%d').date()
        category = request.form.get('category')
        payment = UpcomingPayment(user_id=uid, title=title, amount=amount, due_date=due_date, category=category)
        db.session.add(payment)
        db.session.commit()
        flash('Debt added successfully', 'success')
        return redirect(url_for('debts.list_debts'))
    return render_template('add_debt.html')

@debts_bp.route('/delete/<int:id>', methods=['POST', 'GET'])
def delete_debt(id):
    uid = session['user_id']
    debt = UpcomingPayment.query.filter_by(id=id, user_id=uid).first()
    if debt is None:
        flash('Debt not found', 'error')
        return redirect(url_for('debts.list_debts'))
    db.session.delete(debt)
    db.session.commit()
    flash('Debt deleted successfully', 'success')
    return redirect(request.referrer or url_for('debts.list_debts'))

@debts_bp.route('/pay/<int:id>', methods=['POST', 'GET'])
def mark_debt_paid(id):
    uid = session['user_id']
    debt = UpcomingPayment.query.filter_by(id=id, user_id=uid).first()
    if debt is None:
        flash('Debt not found', 'error')
        return redirect(url_for('debts.list_debts'))

    debt.status = 'paid'

    default_account = Account.query.filter_by(user_id=uid).order_by(Account.id.asc()).first()
    if default_account is not None:
        txn = Transaction(
            user_id=uid,
            account_id=default_account.id,
            type='expense',
            amount=debt.amount,
            category=debt.category or 'Debt',
            description='Borç: %s (autogenerated)' % debt.title,
            date=datetime.now().date()
        )
        db.session.add(txn)
        default_account.current_balance -= debt.amount

    db.session.commit()
    flash('Debt marked as paid', 'success')
    return redirect(request.referrer or url_for('debts.list_debts'))