import os
from flask import Blueprint, render_template, request, redirect, url_for, flash, session
from models import db, UpcomingPayment, Transaction, Account
from datetime import datetime

payments_bp = Blueprint('payments', __name__)

@payments_bp.route('/')
def list_payments():
    uid = session['user_id']
    payments = UpcomingPayment.query.filter_by(user_id=uid).order_by(UpcomingPayment.due_date.asc()).all()
    return render_template('payments.html', payments=payments)

@payments_bp.route('/add', methods=['GET', 'POST'])
def add_payment():
    if request.method == 'POST':
        uid = session['user_id']
        title = request.form.get('title')
        amount = float(request.form.get('amount'))
        due_date_str = request.form.get('due_date')
        due_date = datetime.strptime(due_date_str, '%Y-%m-%d').date()
        category = request.form.get('category')
        payment = UpcomingPayment(user_id=uid, title=title, amount=amount, due_date=due_date, category=category)
        db.session.add(payment)
        db.session.commit()
        flash('Payment added successfully', 'success')
        return redirect(url_for('payments.list_payments'))
    return render_template('add_payment.html')

@payments_bp.route('/delete/<int:id>', methods=['POST', 'GET'])
def delete_payment(id):
    uid = session['user_id']
    payment = UpcomingPayment.query.filter_by(id=id, user_id=uid).first()
    if payment is None:
        flash('Payment not found', 'error')
        return redirect(url_for('payments.list_payments'))
    db.session.delete(payment)
    db.session.commit()
    flash('Payment deleted successfully', 'success')
    return redirect(request.referrer or url_for('payments.list_payments'))

@payments_bp.route('/pay/<int:id>', methods=['POST', 'GET'])
def mark_payment_paid(id):
    uid = session['user_id']
    payment = UpcomingPayment.query.filter_by(id=id, user_id=uid).first()
    if payment is None:
        flash('Payment not found', 'error')
        return redirect(url_for('payments.list_payments'))

    payment.status = 'paid'

    default_account = Account.query.filter_by(user_id=uid).order_by(Account.id.asc()).first()
    if default_account is not None:
        txn = Transaction(
            user_id=uid,
            account_id=default_account.id,
            type='expense',
            amount=payment.amount,
            category=payment.category or 'Bills',
            description='Ödeme: %s (autogenerated)' % payment.title,
            date=datetime.now().date()
        )
        db.session.add(txn)
        default_account.current_balance -= payment.amount

    db.session.commit()
    flash('Payment marked as paid', 'success')
    return redirect(request.referrer or url_for('payments.list_payments'))